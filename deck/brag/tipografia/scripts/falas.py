#!/usr/bin/env python3
"""Writes falas.js (the speaker notes) from the approved script's "Fala" and "Tempo" of each slide.

Usage: python3 scripts/falas.py <report.md>
"""
import json
import re
import sys
from pathlib import Path

texto = Path(sys.argv[1]).read_text()
blocos = re.findall(r"^## (\d+) · (.+?)\n(.*?)(?=^## )", texto, re.S | re.M)
falas = []
for numero, titulo, corpo in blocos:
    achado = re.search(r"Fala:\n(.*?)\nTempo: (.*?)\n", corpo, re.S)
    linhas = [linha[2:].strip() for linha in achado.group(1).splitlines() if linha.startswith("- ")]
    falas.append({"titulo": f"{numero} · {titulo}", "tempo": achado.group(2), "fala": "\n".join(linhas)})

saida = Path(__file__).resolve().parent.parent / "falas.js"
saida.write_text(
    "// Speaker notes, one per slide, in slide order: the \"Fala\" of the approved script, generated by\n"
    "// scripts/falas.py from data/agroparts-brag-texto/report.md.\n"
    "window.FALAS = " + json.dumps(falas, ensure_ascii=False, indent=2) + ";\n"
)
print(f"{len(falas)} falas em {saida}")
